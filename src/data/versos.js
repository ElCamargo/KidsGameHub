/* O mesmo versículo o dia inteiro, em qualquer perfil do aparelho: é
   versículo do dia, não sorteio a cada toque. Dá para decorar o de hoje. */
export function versoDoDia(lang, quando = new Date()) {
  const dia = Math.floor((quando.getTime() - quando.getTimezoneOffset() * 60000) / 864e5);
  const v = VERSOS[((dia % VERSOS.length) + VERSOS.length) % VERSOS.length];
  return { texto: v[lang] || v.en, ref: v.ref[lang] || v.ref.en };
}
