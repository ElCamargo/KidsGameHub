/* Que princípio é o desta semana, e qual dos sete dias é hoje.
   A semana escolhe o princípio e o dia escolhe o devocional: a família demora
   uma semana inteira numa ideia, que é justamente o método. */
export function devocionalDoDia(quando = new Date()) {
  const d = new Date(quando);
  d.setHours(0, 0, 0, 0);
  const domingo = new Date(d);
  domingo.setDate(domingo.getDate() - domingo.getDay());
  const semana = Math.floor(domingo.getTime() / (7 * 864e5));
  const principio = PRINCIPIOS[((semana % PRINCIPIOS.length) + PRINCIPIOS.length) % PRINCIPIOS.length];
  const dias = DEVOCIONAIS[principio.id];
  return { principio, dia: dias[d.getDay() % dias.length], dia_da_semana: d.getDay() };
}
